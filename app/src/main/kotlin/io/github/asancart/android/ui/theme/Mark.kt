/**
 * The split-duo mark with fills from the theme (BRAND.md "In app code": primary and accent tokens,
 * so light and dark switch the colours). Path data is copied unchanged from asancart/brand
 * `logo/svg/asancart-mark-css.svg` and `asancart-mark-small.svg` (brand commit 2e0d250); never edit
 * it here. BRAND-007: the full mark needs at least 48 dp of width; smaller uses [small] (no chip, wider crack).
 */
@Composable
fun AsancartMark(modifier: Modifier = Modifier, small: Boolean = false, contentDescription: String? = null) {
    val colors = AcTheme.colors
    val vector = remember(small, colors.primary, colors.accent) { markVector(small, colors.primary, colors.accent) }
    Image(imageVector = vector, contentDescription = contentDescription, modifier = modifier)
}

/** Card plus a little margin, as in the design prototype: viewBox 40 110 432 290 of the 512 master. */
private fun markVector(small: Boolean, primary: Color, accent: Color): ImageVector {
    val (left, right) = if (small) SMALL else FULL
    return ImageVector.Builder(
        name = if (small) "AsancartMarkSmall" else "AsancartMark",
        defaultWidth = 43.2.dp,
        defaultHeight = 29.dp,
        viewportWidth = 432f,
        viewportHeight = 290f,
    ).addGroup(translationX = -40f, translationY = -110f)
        .addPath(pathData = addPathNodes(left), pathFillType = PathFillType.EvenOdd, fill = SolidColor(primary))
        .addPath(pathData = addPathNodes(right), pathFillType = PathFillType.EvenOdd, fill = SolidColor(accent))
        .clearGroup()
        .build()
}

