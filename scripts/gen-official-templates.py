"""Writes the official Parser Templates that StubDeviceApi serves as GET /v1/device/parser-templates
(REQ-DEV-004): every template of fixtures/parser-templates/<bank>.json, version 1, published.

Usage: python3 -I scripts/gen-official-templates.py fixtures/parser-templates \
         core/src/main/resources/io/github/asancart/android/core/deviceapi/official-parser-templates.json
"""
import glob, json, os, sys

src, out = sys.argv[1], sys.argv[2]
items = []
for f in sorted(glob.glob(os.path.join(src, "*.json"))):
    d = json.load(open(f, encoding="utf-8"))
    if "bank" not in d:
        continue
    for t in d["templates"]:
        items.append({
            "id": f"{d['bank']['id']}/{t['name']}@1",
            "bank_id": d["bank"]["id"],
            "name": t["name"],
            "version": 1,
            "status": "published",
            "published_at": "2026-11-12T00:00:00Z",
            "retired_at": None,
            "body": t,
        })
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w", encoding="utf-8") as fh:
    json.dump({"about": "Generated by scripts/gen-official-templates.py from fixtures/parser-templates.", "items": items},
              fh, ensure_ascii=False, indent=1)
    fh.write("\n")
print(len(items), "templates")
